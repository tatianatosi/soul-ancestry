export function entradaSku91(sku: string): EntradaDicionarioSku91 | undefined {
  return DICIONARIO_SKUS_91.find((e) => e.sku === sku);
}

export function preListaOperacionalSkus(): EntradaDicionarioSku91[] {
  return DICIONARIO_SKUS_91.filter((e) => e.preListaOperacional);
}

export function aliasesPacoteLegado(): EntradaDicionarioSku91[] {
  return DICIONARIO_SKUS_91.filter((e) => e.aliasLegado);
}

export function skuArquivadoDecisao(sku: string): boolean {
  const e = entradaSku91(sku);
  if (e?.statusMotor === "ARQUIVADO_DECISAO_PROPRIETARIA") return true;
  return !itemPermitidoEmRecomendacaoComercial(sku);
}

export function contarPorStatusMotor(): Record<StatusMotorSku, number> {
  const base = Object.fromEntries(STATUS_MOTOR_SKU.map((s) => [s, 0])) as Record<StatusMotorSku, number>;
  for (const e of DICIONARIO_SKUS_91) base[e.statusMotor] += 1;
  return base;
}

